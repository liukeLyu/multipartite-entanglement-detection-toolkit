"""Exact entanglement of (mixed) qubit stabilizer states.

A mixed stabilizer state on ``n`` qubits is

    rho = 2^{-n} prod_{i=1}^{k} (1 + g_i),

for ``k <= n`` independent, commuting Pauli generators ``g_i`` (``k = n`` is a
pure state). Generators are Pauli strings such as ``"XZZXI"``, with an optional
leading sign (``"-XXI"``, ``"+ZZ"``). Character ``j`` acts on qubit ``j``, and
qubit 0 is the most significant tensor factor, as in :mod:`medt.linalg`: the
dense matrix of ``"XZ"`` is ``np.kron(X, Z)``.

Everything here works with the binary symplectic form (x|z bits) and GF(2)
linear algebra, so it scales to hundreds of qubits. For a cut ``A | rest``, let
``J`` be the matrix with ``J_ij = 1`` iff the restrictions of ``g_i`` and ``g_j``
to ``A`` anticommute. Then

* the state is locally equivalent to ``rank(J)/2`` Bell pairs times a separable
  state [1], so it is entangled across the cut iff ``J != 0``;
* the log negativity is ``E_N = log2 ||rho^{T_A}||_1 = rank_F2(J) / 2`` [2, 3].

The rank of ``J`` does not depend on the generating set (``J -> C J C^T``), and
signs do not enter. A state is biseparable iff some bipartition has ``J = 0``:
any biseparable decomposition consists of states with ``<g> = 1`` for every
stabilizer ``g``, so it lives in the code space, and a product vector there is a
common eigenvector of the restricted stabilizers, which is impossible if two of
them anticommute. This is the subspace criterion of [4], Theorem 1 and
Corollary 1, applied to the code space of ``rho``. Reduced states of stabilizer
states are again stabilizer states, generated by the stabilizers that act
trivially outside the region [5].

[1] K. M. R. Audenaert, M. B. Plenio, New J. Phys. 7, 170 (2005), arXiv:quant-ph/0505036.
[2] B. Shi, X. Dai, Y.-M. Lu, arXiv:2012.00040, Theorem A.1.
[3] S. Sang, Y. Li, T. Zhou, X. Chen, T. H. Hsieh, M. P. A. Fisher, PRX Quantum 2, 030313 (2021),
    arXiv:2012.00031.
[4] O. Makuta, B. Kuzaka, R. Augusiak, Quantum 7, 915 (2023), arXiv:2203.16902.
[5] A. Hamma, R. Ionicioiu, P. Zanardi, PRA 71, 022315 (2005), arXiv:quant-ph/0409073.
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np

from medt.linalg import bipartitions

_BITS = {"I": (0, 0), "X": (1, 0), "Y": (1, 1), "Z": (0, 1)}
_LETTERS = {v: k for k, v in _BITS.items()}
_MATRICES = {
    "I": np.eye(2, dtype=complex),
    "X": np.array([[0, 1], [1, 0]], dtype=complex),
    "Y": np.array([[0, -1j], [1j, 0]]),
    "Z": np.diag([1, -1]).astype(complex),
}


def _rank_f2(M: np.ndarray) -> int:
    """Rank over GF(2) of a 0/1 matrix."""
    M = np.array(M, dtype=np.uint8) % 2
    rank = 0
    for col in range(M.shape[1]):
        pivots = np.flatnonzero(M[rank:, col]) + rank
        if pivots.size == 0:
            continue
        M[[rank, pivots[0]]] = M[[pivots[0], rank]]
        below = np.flatnonzero(M[:, col])
        below = below[below != rank]
        M[below] ^= M[rank]
        rank += 1
        if rank == M.shape[0]:
            break
    return rank


def _left_null_space_f2(M: np.ndarray) -> np.ndarray:
    """Rows ``c`` spanning ``{c : c M = 0 mod 2}``."""
    k = M.shape[0]
    A = np.concatenate([np.array(M, dtype=np.uint8) % 2, np.eye(k, dtype=np.uint8)], axis=1)
    m = M.shape[1]
    rank = 0
    for col in range(m):
        pivots = np.flatnonzero(A[rank:, col]) + rank
        if pivots.size == 0:
            continue
        A[[rank, pivots[0]]] = A[[pivots[0], rank]]
        others = np.flatnonzero(A[:, col])
        others = others[others != rank]
        A[others] ^= A[rank]
        rank += 1
        if rank == k:
            break
    return A[rank:, m:]


def _parse(generators: Sequence[str], n: int | None = None):
    """Bits ``x, z`` of shape (k, n) and phase exponents ``e`` (0 or 2) of the Pauli strings.

    A string means ``i^e`` times the tensor product of its letters.
    """
    if isinstance(generators, str):
        raise TypeError("generators must be a sequence of Pauli strings, not a single string")
    rows, phases = [], []
    for g in generators:
        g = str(g).strip().upper()
        e = 0
        if g[:1] in "+-":
            e, g = (2 if g[0] == "-" else 0), g[1:]
        if not g or any(c not in _BITS for c in g):
            raise ValueError(f"{g!r} is not a Pauli string over I, X, Y, Z")
        rows.append([_BITS[c] for c in g])
        phases.append(e)
    if rows:
        lengths = {len(r) for r in rows}
        if len(lengths) > 1:
            raise ValueError(f"generators have different lengths {sorted(lengths)}")
        if n is not None and lengths != {n}:
            raise ValueError(f"generators act on {lengths.pop()} qubits, not n={n}")
        n = len(rows[0])
    elif n is None:
        raise ValueError("give n when there are no generators")
    bits = np.array(rows, dtype=np.uint8).reshape(len(rows), n, 2)
    return bits[..., 0], bits[..., 1], np.array(phases, dtype=np.int64)


def _commutation(x: np.ndarray, z: np.ndarray) -> np.ndarray:
    """``J_ij = 1`` iff Paulis ``i`` and ``j`` anticommute (symplectic product)."""
    x, z = x.astype(np.int64), z.astype(np.int64)
    return (x @ z.T + z @ x.T) % 2


def _check(generators: Sequence[str], n: int | None = None):
    x, z, e = _parse(generators, n)
    if _commutation(x, z).any():
        raise ValueError("generators do not commute pairwise")
    if _rank_f2(np.concatenate([x, z], axis=1)) < len(e):
        raise ValueError("generators are not independent over GF(2)")
    return x, z, e


def _mul(x1, z1, e1, x2, z2, e2):
    """Product of two Pauli strings in the ``(x, z, e)`` form of :func:`_parse`."""
    a1, b1, a2, b2 = (np.asarray(v, dtype=np.int64) for v in (x1, z1, x2, z2))
    x3, z3 = a1 ^ a2, b1 ^ b2
    # Each letter is i^{xz} X^x Z^z, and Z^z1 X^x2 = (-1)^{z1 x2} X^x2 Z^z1.
    e = e1 + e2 + int((a1 * b1 + a2 * b2 + 2 * b1 * a2 - x3 * z3).sum())
    return x3.astype(np.uint8), z3.astype(np.uint8), e % 4


def _strings(x: np.ndarray, z: np.ndarray, e: np.ndarray) -> list[str]:
    out = []
    for xi, zi, ei in zip(x, z, e, strict=True):
        if ei % 2:
            raise ValueError("Pauli string with an imaginary phase is not Hermitian")
        out.append(("-" if ei % 4 == 2 else "") + "".join(_LETTERS[(a, b)] for a, b in zip(xi, zi, strict=True)))
    return out


def stabilizer_dm(generators: Sequence[str], n: int | None = None) -> np.ndarray:
    """Dense density matrix ``2^{-n} prod_i (1 + g_i)``; for small ``n`` only.

    ``n`` is needed only when ``generators`` is empty (the maximally mixed state).
    """
    x, z, e = _check(generators, n)
    n = x.shape[1]
    rho = np.eye(2**n, dtype=complex) / 2**n
    for xi, zi, ei in zip(x, z, e, strict=True):
        g = np.ones((1, 1), dtype=complex)
        for a, b in zip(xi, zi, strict=True):
            g = np.kron(g, _MATRICES[_LETTERS[(a, b)]])
        rho = rho + (1j**ei) * (g @ rho)
    return rho


def _cut_rank(x: np.ndarray, z: np.ndarray, sys: Sequence[int]) -> int:
    sys = sorted({int(s) for s in sys})
    if any(not 0 <= s < x.shape[1] for s in sys):
        raise ValueError(f"sys={sys} is out of range for {x.shape[1]} qubits")
    return _rank_f2(_commutation(x[:, sys], z[:, sys]))


def stabilizer_log_negativity(generators: Sequence[str], sys: Sequence[int]) -> float:
    """Log negativity ``log2 ||rho^{T_sys}||_1 = rank_F2(J) / 2`` across ``sys | rest`` [2, 3].

    Same units as :func:`medt.log_negativity`. ``J`` is the commutation matrix of
    the generators restricted to ``sys``.
    """
    x, z, _ = _check(generators)
    return _cut_rank(x, z, sys) / 2


def stabilizer_negativity(generators: Sequence[str], sys: Sequence[int]) -> float:
    """Negativity ``(||rho^{T_sys}||_1 - 1) / 2 = (2^{E_N} - 1) / 2``, as :func:`medt.negativity`."""
    return (2 ** stabilizer_log_negativity(generators, sys) - 1) / 2


def stabilizer_entangled(generators: Sequence[str], sys: Sequence[int]) -> bool:
    """Whether the state is entangled across ``sys | rest``, i.e. ``J != 0`` [1]."""
    x, z, _ = _check(generators)
    sys = sorted({int(s) for s in sys})
    return bool(_commutation(x[:, sys], z[:, sys]).any())


def stabilizer_is_gme(generators: Sequence[str], parties: Sequence[Sequence[int]] | None = None) -> bool:
    """Whether the state is genuinely multipartite entangled among ``parties`` [4].

    ``parties`` partitions the qubits into at least two groups (default: one
    qubit per party). The state is GME iff every bipartition of the parties has
    ``J != 0``; otherwise it is separable across a cut with ``J = 0``.
    """
    x, z, _ = _check(generators)
    n = x.shape[1]
    if parties is None:
        parties = [[q] for q in range(n)]
    parties = [[int(q) for q in p] for p in parties]
    flat = [q for p in parties for q in p]
    if sorted(flat) != list(range(n)) or any(not p for p in parties):
        raise ValueError(f"parties {parties} do not partition the {n} qubits into nonempty groups")
    if len(parties) < 2:
        raise ValueError("need at least two parties")
    for M in bipartitions(len(parties)):
        sys = [q for m in M for q in parties[m]]
        if not _commutation(x[:, sys], z[:, sys]).any():
            return False
    return True


def stabilizer_restrict(generators: Sequence[str], keep: Sequence[int]) -> list[str]:
    """Generators of the reduced state on the qubits ``keep``, relabelled ``0..len(keep)-1`` in that order.

    They generate the stabilizers that act as the identity outside ``keep`` [5],
    found as the GF(2) left null space of the generators' bits outside ``keep``.
    An empty list means the reduced state is maximally mixed.
    """
    x, z, e = _check(generators)
    n = x.shape[1]
    keep = [int(q) for q in keep]
    if len(set(keep)) != len(keep) or any(not 0 <= q < n for q in keep):
        raise ValueError(f"keep={keep} is not a list of distinct qubits of {n}")
    out = [q for q in range(n) if q not in set(keep)]
    combos = _left_null_space_f2(np.concatenate([x[:, out], z[:, out]], axis=1))
    rows = []
    for c in combos:
        px, pz, pe = np.zeros(n, dtype=np.uint8), np.zeros(n, dtype=np.uint8), 0
        for i in np.flatnonzero(c):
            px, pz, pe = _mul(px, pz, pe, x[i], z[i], e[i])
        rows.append((px[keep], pz[keep], pe))
    if not rows:
        return []
    return _strings(np.array([r[0] for r in rows]), np.array([r[1] for r in rows]), np.array([r[2] for r in rows]))
